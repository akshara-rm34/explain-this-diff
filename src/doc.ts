// Builds and updates the per-repo interview prep markdown doc. Each PR gets
// one section between markers, so answering again replaces the old entry.

import type { Feedback, Question } from "./llm.js";

export interface Entry {
  prNumber: number;
  title: string;
  url: string;
  date: string; // YYYY-MM-DD
  questions: Question[];
  answers: string[];
  feedback: Feedback[] | null;
}

const start = (n: number) => `<!-- etd:pr-${n} -->`;
const end = (n: number) => `<!-- /etd:pr-${n} -->`;

export function docHeader(repo: string): string {
  return `# Interview prep: ${repo}

Questions about my own pull requests, with my answers. Generated by Explain This Diff.
`;
}

function quote(text: string): string {
  return (text || "_(no answer)_")
    .split("\n")
    .map((l) => `> ${l}`)
    .join("\n");
}

export function renderEntry(e: Entry): string {
  const items = e.questions
    .map((q, i) => {
      const fb = e.feedback?.[i];
      const fbBlock = fb
        ? `\n\n*Feedback (${fb.verdict}):* ${fb.feedback}\n\n*Stronger answer:* ${fb.stronger_answer}`
        : "";
      return `**Q${i + 1}.** ${q.question} <sub>\`${q.file}\`</sub>\n\n${quote(e.answers[i])}${fbBlock}`;
    })
    .join("\n\n");

  return `${start(e.prNumber)}
## [#${e.prNumber}: ${e.title}](${e.url})
<sub>${e.date}</sub>

${items}
${end(e.prNumber)}`;
}

export function upsertEntry(doc: string | null, repo: string, e: Entry): string {
  const section = renderEntry(e);
  const base = doc ?? docHeader(repo);
  const s = base.indexOf(start(e.prNumber));
  const t = base.indexOf(end(e.prNumber));
  if (s !== -1 && t > s) {
    return base.slice(0, s) + section + base.slice(t + end(e.prNumber).length);
  }
  return base.trimEnd() + "\n\n" + section + "\n";
}
